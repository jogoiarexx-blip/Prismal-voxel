'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const store=fs.readFileSync(path.join(root,'js/store.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'js/ui.js'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(store,/hudScale: 1/);
assert.match(store,/highContrast: false/);
assert.match(ui,/Math\.max\(0\.75, Math\.min\(1\.5, Number\(settings\.hudScale\) \|\| 1\)\)/);
assert.match(ui,/--prisma-hud-scale/);
assert.match(ui,/prisma-high-contrast/);
assert.match(ui,/slider\('hudScale', 'Tamanho dos textos do HUD', 0\.75, 1\.5/);
assert.match(ui,/\['highContrast', 'highContrast'\]/);
assert.match(ui,/\['fov', 'sensitivity', 'touchSensitivity', 'touchSize', 'hudScale'/);
assert.match(css,/#gamehud #quest \{font-size:calc\(14px \* var\(--prisma-hud-scale/);
assert.match(css,/body\.prisma-high-contrast #gamehud #cross:before/);
assert.match(css,/body\.prisma-high-contrast #gamehud #houseCompass/);
assert.match(ui,/Persistência:.*regiões alteradas/);
const version=fs.readFileSync(path.join(root,'offline.js'),'utf8').match(/CACHE = PREFIX \+ '(\d+\.\d+\.\d+)'/)[1];
assert.ok(index.includes('VERSÃO '+version),'displayed version matches offline cache');
console.log('PASS accessibility: HUD text scaling, contrast, saved settings, world-edit diagnostic and version');
